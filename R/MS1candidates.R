#' Return default LipidMS adduct table
#'
#' @return `data.frame` with columns `adduct`, `mdiff`, `charge`, and `n`.
#'
#' @examples
#' adducts <- defaultAdductTable()
#' adducts
#'
#' @export
defaultAdductTable <- function() {
  data.frame(
    adduct = c(
      "M-H", "M-H-H2O", "M+CH3COO", "M+HCOO", "M+Na-2H",
      "M-H-2H2O", "M-CH3", "M+H", "M+H-H2O", "M+Na", "M+NH4",
      "M+H-2H2O", "2M+NH4", "2M+Na", "M+H-H2O-NH4", "M-2H",
      "2M-H", "M+CH3COO-CH3", "M-CH3-H2O", "M-CO2-H",
      "M+NaCH3COO", "M"
    ),
    mdiff = c(
      -1.00780, -19.01840, 59.01390, 44.99820, 20.97360,
      -37.02900, -15.02347, 1.00780, -17.00280, 22.98920,
      18.03440, -35.01340, 18.03440, 22.98920, -37.05280,
      -2.01560, -1.00780, 44.99820, -33.03407, -44.99710,
      80.99530, 0
    ),
    charge = c(
      -1L, -1L, -1L, -1L, -1L,
      -1L, -1L, 1L, 1L, 1L, 1L,
      1L, 1L, 1L, 1L, -2L,
      -1L, -1L, -1L, -1L,
      -1L, 1
    ),
    n = c(
      1L, 1L, 1L, 1L, 1L,
      1L, 1L, 1L, 1L, 1L, 1L,
      1L, 2L, 2L, 1L, 1L,
      2L, 1L, 1L, 1L,
      1L, 1
    ),
    stringsAsFactors = FALSE
  )
}

#' Calculate theoretical adduct m/z
#'
#' Calculate theoretical m/z from neutral exact mass and an adduct definition.
#'
#' The adduct table follows the LipidMS convention:
#'
#' `mz = abs((neutral_exact_mass * n + mdiff) / charge)`
#'
#' @param neutral_exact_mass Numeric vector with neutral exact masses.
#' @param adduct `character(1)`. Adduct name (i.e. M-H, M+H, M+CH3COO...).
#' @param adduct_table `data.frame` with columns `adduct`, `mdiff`, `charge`,
#' and `n`.
#'
#' @examples
#' calculateAdductMz(
#'     neutral_exact_mass = 760.585,
#'     adduct = "M-H"
#' )
#'
#' @return Numeric vector with theoretical m/z values.
#'
#' @export
calculateAdductMz <- function(neutral_exact_mass,
                              adduct,
                              adduct_table = defaultAdductTable()) {
  required <- c("adduct", "mdiff", "charge", "n")

  if (!all(required %in% colnames(adduct_table))) {
    stop(
      "'adduct_table' must contain columns: ",
      paste(required, collapse = ", "),
      call. = FALSE
    )
  }

  idx <- match(adduct, adduct_table$adduct)

  if (is.na(idx)) {
    stop("Unsupported adduct: ", adduct, call. = FALSE)
  }

  mdiff <- adduct_table$mdiff[[idx]]
  charge <- adduct_table$charge[[idx]]
  n <- adduct_table$n[[idx]]

  abs((neutral_exact_mass * n + mdiff) / charge)
}

#' Combine lipid databases
#'
#' Combine the lipid database list generated by `createLipidDbs()` into one
#' `data.frame`.
#'
#' @param dbs Object returned by `createLipidDbs()`.
#'
#' @return Combined lipid database `data.frame`.
#'
#' @noRd
#'
#' @keywords internal
.combine_lipid_dbs <- function(dbs) {
  if (!is.list(dbs) || !"dbs" %in% names(dbs)) {
    stop("'dbs' must be the object returned by createLipidDbs().",
         call. = FALSE)
  }

  out <- do.call(rbind, dbs$dbs)

  if (is.null(out) || !nrow(out)) {
    stop("'dbs$dbs' does not contain lipid entries.", call. = FALSE)
  }

  required <- c(
    "class", "sum_composition", "molecular_formula", "neutral_exact_mass"
  )

  missing <- setdiff(required, colnames(out))
  if (length(missing)) {
    stop(
      "Combined lipid database is missing columns: ",
      paste(missing, collapse = ", "),
      call. = FALSE
    )
  }

  rownames(out) <- NULL
  out
}

#' Filter class-adduct table by polarity
#'
#' @param dbs Object returned by `createLipidDbs()`.
#' @param polarity `character(1)`. Polarity to keep, usually `"positive"` or
#' `"negative"`.
#'
#' @return `data.frame` with class/adduct pairs.
#'
#' @noRd
#'
#' @keywords internal
.get_adducts_by_polarity <- function(dbs, polarity) {
  if (!"adducts" %in% names(dbs)) {
    stop("'dbs' must contain an 'adducts' table.", call. = FALSE)
  }

  adducts <- dbs$adducts

  required <- c("class", "polarity", "adduct")
  missing <- setdiff(required, colnames(adducts))

  if (length(missing)) {
    stop(
      "'dbs$adducts' is missing columns: ",
      paste(missing, collapse = ", "),
      call. = FALSE
    )
  }

  adducts <- adducts[adducts$polarity == polarity, , drop = FALSE]

  if (!nrow(adducts)) {
    stop("No adducts found for polarity: ", polarity, call. = FALSE)
  }

  adducts
}


#' Return chromPeak sample indices
#'
#' @param chrom_peaks Matrix returned by `xcms::chromPeaks()`.
#'
#' @return Integer vector with sample index per chromPeak.
#'
#' @noRd
#'
#' @keywords internal
.get_chrom_peak_sample_idx <- function(chrom_peaks) {
  if ("sample" %in% colnames(chrom_peaks)) {
    return(as.integer(chrom_peaks[, "sample"]))
  }

  if ("sampleidx" %in% colnames(chrom_peaks)) {
    return(as.integer(chrom_peaks[, "sampleidx"]))
  }

  stop("Could not find sample index in chromPeaks().", call. = FALSE)
}

#' Return an empty MS1 candidate table
#'
#' @return Empty `data.frame` with MS1 candidate columns.
#'
#' @noRd
#'
#' @keywords internal
.empty_ms1_candidate_table <- function() {
  data.frame(
    chrom_peak_id = character(),
    sample = integer(),
    mz = numeric(),
    rt = numeric(),
    rtmin = numeric(),
    rtmax = numeric(),
    class = character(),
    sum_composition = character(),
    carbon = numeric(),
    double_bond = numeric(),
    oxygen = numeric(),
    molecular_formula = character(),
    neutral_exact_mass = numeric(),
    adduct = character(),
    adduct_priority = integer(),
    exclude_if_unique = integer(),
    adduct_score = numeric(),
    observed_neutral_mass = numeric(),
    neutral_mass_error_ppm = numeric(),
    theoretical_mz = numeric(),
    ppm_error = numeric(),
    adduct_group_id = character(),
    stringsAsFactors = FALSE
  )
}

#' Build theoretical lipid-adduct table
#'
#' @param dbs Object returned by `createLipidDbs()`.
#' @param paramannot Annotation parameter list with `polarity`.
#' @param adduct_table Adduct definition table.
#'
#' @examples
#' dbs <- createLipidDbs(
#'     lipid_classes = c("PC", "PE")
#' )
#'
#' param <- defaultAnnotationParameters("negative")
#'
#' theoretical_db <- build_theoretical_adduct_db(
#'     dbs = dbs,
#'     paramannot = param
#' )
#'
#' head(theoretical_db)
#'
#' @return `data.frame` sorted by `theoretical_mz`.
#'
#' @export
build_theoretical_adduct_db <- function(dbs,
                                         paramannot,
                                         adduct_table = defaultAdductTable()) {
  db_all <- .combine_lipid_dbs(dbs)

  adducts <- .get_adducts_by_polarity(
    dbs = dbs,
    polarity = paramannot$polarity
  )

  out <- vector("list", nrow(adducts))
  k <- 1L

  for (i in seq_len(nrow(adducts))) {
    class_i <- adducts$class[[i]]
    adduct_i <- adducts$adduct[[i]]
    adduct_priority_i <- adducts$adduct_priority[[i]]
    exclude_if_unique_i <- if ("exclude_if_unique" %in% colnames(adducts)) {
      adducts$exclude_if_unique[[i]]
    } else {
      0L
    }

    db_i <- db_all[db_all$class == class_i, , drop = FALSE]

    if (!nrow(db_i)) {
      next
    }

    theo_mz <- calculateAdductMz(
      neutral_exact_mass = db_i$neutral_exact_mass,
      adduct = adduct_i,
      adduct_table = adduct_table
    )

    out[[k]] <- data.frame(
      class = db_i$class,
      sum_composition = db_i$sum_composition,
      n_carbon = db_i$n_carbon,
      n_double_bond = db_i$n_double_bond,
      n_oxygen = db_i$n_oxygen,
      molecular_formula = db_i$molecular_formula,
      neutral_exact_mass = db_i$neutral_exact_mass,
      adduct = adduct_i,
      adduct_priority = adduct_priority_i,
      exclude_if_unique = exclude_if_unique_i,
      theoretical_mz = theo_mz,
      stringsAsFactors = FALSE
    )

    k <- k + 1L
  }

  out <- do.call(rbind, out[seq_len(k - 1L)])
  out <- out[order(out$theoretical_mz), , drop = FALSE]
  rownames(out) <- NULL
  out
}

#' Find MS1 lipid candidates
#'
#' Fast MS1 candidate search using a precomputed theoretical lipid-adduct table
#' and sorted m/z interval lookup.
#'
#' If `paramannot$remove_isotopes` is `TRUE`, peaks flagged as isotopes through
#' `is_isotope` are excluded.
#'
#' @param x `XcmsExperiment`.
#' @param dbs Object returned by `createLipidDbs()`.
#' @param paramannot Annotation parameter list. Requires `polarity` and
#' `dmzprecursor`.
#' @param adduct_table Adduct definition table.
#'
#' @examples
#' data(xcmsexperiment_negative)
#'
#' param <- defaultAnnotationParameters("negative")
#' dbs <- createLipidDbs()
#'
#' candidates <- findMs1LipidCandidates(
#'     x = xcmsexperiment_negative,
#'     dbs = dbs,
#'     paramannot = param
#' )
#'
#' head(candidates)
#'
#' @return `data.frame` with MS1 lipid candidates.
#'
#' @export
findMs1LipidCandidates <- function(x,
                                   dbs,
                                   paramannot,
                                   adduct_table = defaultAdductTable()) {
  cp <- xcms::chromPeaks(x)
  cpd <- as.data.frame(xcms::chromPeakData(x))

  if (!nrow(cp)) {
    stop("'x' does not contain chromPeaks.", call. = FALSE)
  }

  if (is.null(paramannot$polarity)) {
    stop("'paramannot$polarity' is required.", call. = FALSE)
  }

  if (is.null(paramannot$dmzprecursor)) {
    stop("'paramannot$dmzprecursor' is required.", call. = FALSE)
  }

  if (nrow(cpd) != nrow(cp)) {
    stop("chromPeakData and chromPeaks are not aligned.", call. = FALSE)
  }

  keep <- rep(TRUE, nrow(cp))

  if ("is_isotope" %in% colnames(cpd)) {
    iso <- cpd$is_isotope

    if (is.factor(iso)) {
      iso <- as.character(iso)
    }

    if (is.character(iso)) {
      iso <- iso %in% c("TRUE", "T", "1", "yes", "Y")
    }

    iso[is.na(iso)] <- FALSE

    if (isTRUE(paramannot$only_confirmed_monoisotopic)) {
      if (!"isotope_rank" %in% colnames(cpd)) {
        stop(
          paste(
            "'only_confirmed_monoisotopic = TRUE' requires",
            "'isotope_rank' in chromPeakData(x)."
          ),
          call. = FALSE
        )
      }

      isotope_rank <- as.character(cpd$isotope_rank)

      valid_rank <- is.na(isotope_rank) | grepl("^[0-9]+$", isotope_rank)

      if (!all(valid_rank)) {
        stop(
          "'isotope_rank' contains non-integer values.",
          call. = FALSE
        )
      }

      isotope_rank <- as.integer(isotope_rank)

      keep <- !iso &
        !is.na(isotope_rank) &
        isotope_rank == 0L
    } else if (isTRUE(paramannot$remove_isotopes)) {
      keep <- !iso
    }
  }

  cp_use <- cp[keep, , drop = FALSE]

  if (!nrow(cp_use)) {
    return(.empty_ms1_candidate_table())
  }

  theoretical_db <- build_theoretical_adduct_db(
    dbs = dbs,
    paramannot = paramannot,
    adduct_table = adduct_table
  )

  theo_mz <- theoretical_db$theoretical_mz
  sample_idx <- .get_chrom_peak_sample_idx(cp_use)

  mz <- cp_use[, "mz"]
  mz_tol <- mz * paramannot$dmzprecursor / 1e6

  lower <- mz - mz_tol
  upper <- mz + mz_tol

  left <- findInterval(lower, theo_mz) + 1L
  right <- findInterval(upper, theo_mz)

  n_hits <- pmax(right - left + 1L, 0L)

  if (!any(n_hits > 0L)) {
    return(.empty_ms1_candidate_table())
  }

  peak_rep <- rep(which(n_hits > 0L), n_hits[n_hits > 0L])

  db_idx <- unlist(
    mapply(
      seq.int,
      from = left[n_hits > 0L],
      to = right[n_hits > 0L],
      SIMPLIFY = FALSE,
      USE.NAMES = FALSE
    ),
    use.names = FALSE
  )

  peak_mz <- mz[peak_rep]
  theoretical_mz <- theoretical_db$theoretical_mz[db_idx]
  neutral_exact_mass <- theoretical_db$neutral_exact_mass[db_idx]
  adduct <- theoretical_db$adduct[db_idx]
  adduct_priority <- theoretical_db$adduct_priority[db_idx]
  exclude_if_unique <- theoretical_db$exclude_if_unique[db_idx]

  observed_neutral_mass <- calculateNeutralMassFromAdduct(
    mz = peak_mz,
    adduct = adduct,
    adduct_table = adduct_table
  )

  neutral_mass_error_ppm <- (
    observed_neutral_mass - neutral_exact_mass
  ) / neutral_exact_mass * 1e6

  out <- data.frame(
    chrom_peak_id = rownames(cp_use)[peak_rep],
    sample = sample_idx[peak_rep],
    mz = peak_mz,
    rt = cp_use[peak_rep, "rt"],
    rtmin = cp_use[peak_rep, "rtmin"],
    rtmax = cp_use[peak_rep, "rtmax"],
    class = theoretical_db$class[db_idx],
    sum_composition = theoretical_db$sum_composition[db_idx],
    carbon = theoretical_db$n_carbon[db_idx],
    double_bond = theoretical_db$n_double_bond[db_idx],
    oxygen = theoretical_db$n_oxygen[db_idx],
    molecular_formula = theoretical_db$molecular_formula[db_idx],
    neutral_exact_mass = neutral_exact_mass,
    adduct = adduct,
    adduct_priority = adduct_priority,
    exclude_if_unique = exclude_if_unique,
    adduct_score = 1 / adduct_priority,
    observed_neutral_mass = observed_neutral_mass,
    neutral_mass_error_ppm = neutral_mass_error_ppm,
    theoretical_mz = theoretical_mz,
    ppm_error = (peak_mz - theoretical_mz) / theoretical_mz * 1e6,
    adduct_group_id = NA_character_,
    stringsAsFactors = FALSE
  )

  rownames(out) <- NULL
  out
}

#' Group coeluting adduct candidates
#'
#' Group MS1 candidates with the same sample, lipid class and sum composition
#' only when all apex RT differences within the group are below `rttol / 2` and
#' all grouped candidates correspond to different adducts.
#'
#' @param candidates `data.frame` returned by [findMs1LipidCandidates()].
#' @param paramannot Annotation parameter list. Requires `rttol`.
#'
#' @examples
#' data(xcmsexperiment_negative)
#'
#' param <- defaultAnnotationParameters("negative")
#' dbs <- createLipidDbs()
#'
#' candidates <- findMs1LipidCandidates(
#'     xcmsexperiment_negative,
#'     dbs,
#'     param
#' )
#'
#' candidates <- groupCoelutingAdducts(
#'     candidates,
#'     param
#' )
#'
#' head(candidates)
#'
#' @return Candidate table with updated `adduct_group_id`.
#'
#' @export
groupCoelutingAdducts <- function(candidates, paramannot) {
  if (!nrow(candidates)) {
    candidates$adduct_group_id <- character()
    return(candidates)
  }

  if (is.null(paramannot$rttol)) {
    stop("'paramannot$rttol' is required.", call. = FALSE)
  }

  candidates$adduct_group_id <- NA_character_
  rt_tol <- paramannot$rttol / 2

  split_key <- paste(
    candidates$sample,
    candidates$class,
    candidates$sum_composition,
    sep = "|"
  )

  groups <- split(seq_len(nrow(candidates)), split_key)
  group_id <- 1L

  for (idx in groups) {
    idx <- idx[order(candidates$rt[idx])]

    active_groups <- list()

    for (ii in idx) {
      assigned <- FALSE

      if (length(active_groups)) {
        for (g in seq_along(active_groups)) {
          group_idx <- active_groups[[g]]

          different_adduct <- !candidates$adduct[[ii]] %in%
            candidates$adduct[group_idx]

          rt_ok <- all(
            abs(candidates$rt[ii] - candidates$rt[group_idx]) < rt_tol,
            na.rm = FALSE
          )

          if (different_adduct && rt_ok) {
            active_groups[[g]] <- c(group_idx, ii)
            assigned <- TRUE
            break
          }
        }
      }

      if (!assigned) {
        active_groups[[length(active_groups) + 1L]] <- ii
      }
    }

    for (g in seq_along(active_groups)) {
      candidates$adduct_group_id[active_groups[[g]]] <-
        paste0("AG", group_id)
      group_id <- group_id + 1L
    }
  }

  candidates <- .score_adduct_groups(candidates)
  candidates <- .filter_unique_unsupported_adducts(candidates)
  candidates <- .filter_incompatible_peak_candidates(candidates)

  candidates
}

#' Calculate neutral mass from observed adduct m/z
#'
#' Reconstruct the neutral exact mass from an observed m/z value and an adduct
#' definition.
#'
#' The adduct table follows the LipidMS convention:
#'
#' `mz = abs((neutral_exact_mass * n + mdiff) / charge)`
#'
#' This function applies the inverse calculation:
#'
#' `neutral_exact_mass = (mz * abs(charge) - mdiff) / n`
#'
#' @param mz Numeric vector with observed m/z values.
#' @param adduct Character vector with adduct names.
#' @param adduct_table `data.frame` with columns `adduct`, `mdiff`, `charge`
#' and `n`.
#'
#' @examples
#' neutral_mass <- 760.585
#'
#' mz <- calculateAdductMz(
#'     neutral_exact_mass = neutral_mass,
#'     adduct = "M-H"
#' )
#'
#' calculateNeutralMassFromAdduct(
#'     mz = mz,
#'     adduct = "M-H"
#' )
#'
#' @return Numeric vector with reconstructed neutral masses.
#'
#' @export
calculateNeutralMassFromAdduct <- function(mz,
                                           adduct,
                                           adduct_table = defaultAdductTable()) {
  required <- c("adduct", "mdiff", "charge", "n")

  if (!all(required %in% colnames(adduct_table))) {
    stop(
      "'adduct_table' must contain columns: ",
      paste(required, collapse = ", "),
      call. = FALSE
    )
  }

  idx <- match(adduct, adduct_table$adduct)

  if (anyNA(idx)) {
    stop("Unsupported adduct found.", call. = FALSE)
  }

  mdiff <- adduct_table$mdiff[idx]
  charge <- adduct_table$charge[idx]
  n <- adduct_table$n[idx]

  (mz * abs(charge) - mdiff) / n
}

#' Score coeluting adduct groups
#'
#' Calculate adduct-support scores for each candidate within each adduct group.
#'
#' Candidates are grouped by `adduct_group_id`, lipid class, sum composition and
#' theoretical neutral exact mass. The adduct group score is calculated as the
#' sum of individual adduct scores, where each adduct score is usually derived
#' from adduct priority as `1 / adduct_priority`.
#'
#' The number of unique adducts supporting each candidate is also calculated and
#' stored as an additional tie-breaking metric.
#'
#' @param candidates `data.frame` returned by [groupCoelutingAdducts()] after
#' adduct grouping. Must contain columns `class`, `sum_composition`,
#' `neutral_exact_mass`, `adduct`, `adduct_group_id` and `adduct_score`.
#'
#' @return Candidate table with two additional columns:
#' `adduct_group_score` and `adduct_group_n_adducts`.
#'
#' @noRd
#'
#' @keywords internal
.score_adduct_groups <- function(candidates) {
  if (!nrow(candidates)) {
    return(candidates)
  }

  candidates$adduct_score[is.na(candidates$adduct_score)] <- 0

  candidate_key <- paste(
    candidates$class,
    candidates$sum_composition,
    format(candidates$neutral_exact_mass, digits = 12, trim = TRUE),
    sep = "|"
  )

  group_key <- paste(
    candidates$adduct_group_id,
    candidate_key,
    sep = "|"
  )

  group_score <- stats::ave(
    candidates$adduct_score,
    group_key,
    FUN = function(z) sum(z, na.rm = TRUE)
  )

  group_n_adducts <- stats::ave(
    candidates$adduct,
    group_key,
    FUN = function(z) length(unique(z))
  )

  candidates$adduct_group_score <- as.numeric(group_score)
  candidates$adduct_group_n_adducts <- as.integer(group_n_adducts)

  candidates
}

#' Filter incompatible candidates explaining the same chromatographic peak
#'
#' For each chromatographic peak, keep only the candidate or candidates with the
#' strongest adduct support, even if they correspond to different lipid
#' compositions. This resolves cases where the same observed peak can be
#' explained by alternative lipid/adduct hypotheses, such as PC(34:1) M+CH3COO
#' versus PC(35:1) M+CH3COO-CH3.
#'
#' Candidates are ranked by:
#' 1. highest adduct group score,
#' 2. highest number of supporting adducts,
#' 3. best adduct priority,
#' 4. lowest absolute ppm error.
#'
#' @param candidates `data.frame` containing MS1 lipid candidates and
#'   adduct-group information.
#'
#' @noRd
#'
#' @keywords internal
.filter_incompatible_peak_candidates <- function(candidates) {
  if (!nrow(candidates)) {
    return(candidates)
  }

  required <- c(
    "chrom_peak_id",
    "adduct_group_id",
    "adduct_group_score",
    "adduct_group_n_adducts",
    "adduct_priority"
  )

  missing <- setdiff(required, colnames(candidates))
  if (length(missing)) {
    stop(
      "'candidates' is missing columns: ",
      paste(missing, collapse = ", "),
      call. = FALSE
    )
  }

  all_groups <- unique(candidates$adduct_group_id)
  all_groups <- all_groups[!is.na(all_groups)]

  losing_groups <- character()
  peak_groups <- split(seq_len(nrow(candidates)), candidates$chrom_peak_id)

  for (idx in peak_groups) {
    group_ids <- unique(candidates$adduct_group_id[idx])
    group_ids <- group_ids[!is.na(group_ids)]

    if (length(group_ids) <= 1L) {
      next
    }

    z <- candidates[idx, , drop = FALSE]

    group_summary <- stats::aggregate(
      cbind(
        adduct_group_score,
        adduct_group_n_adducts
      ) ~ adduct_group_id,
      data = z,
      FUN = max,
      na.rm = TRUE
    )

    group_priority <- stats::aggregate(
      adduct_priority ~ adduct_group_id,
      data = z,
      FUN = min,
      na.rm = TRUE
    )

    group_summary <- merge(
      group_summary,
      group_priority,
      by = "adduct_group_id",
      all.x = TRUE
    )

    best_score <- max(group_summary$adduct_group_score, na.rm = TRUE)
    best <- group_summary[
      group_summary$adduct_group_score == best_score,
      ,
      drop = FALSE
    ]

    if (nrow(best) > 1L) {
      best_n <- max(best$adduct_group_n_adducts, na.rm = TRUE)
      best <- best[best$adduct_group_n_adducts == best_n, , drop = FALSE]
    }

    if (nrow(best) > 1L) {
      best_priority <- min(best$adduct_priority, na.rm = TRUE)
      best <- best[best$adduct_priority == best_priority, , drop = FALSE]
    }

    winner_groups <- unique(best$adduct_group_id)

    if (length(winner_groups) < length(group_ids)) {
      losing_groups <- c(
        losing_groups,
        setdiff(group_ids, winner_groups)
      )
    }
  }

  losing_groups <- unique(losing_groups)

  keep <- !candidates$adduct_group_id %in% losing_groups

  candidates[keep, , drop = FALSE]
}

#' Add compact MS1 candidate summary to chromPeakData
#'
#' Add only compact candidate information to `chromPeakData()`. The full
#' candidate table should be kept separately until final lipid annotation.
#'
#' @param x `XcmsExperiment`.
#' @param candidates Candidate table returned by [findMs1LipidCandidates()].
#'
#' @examples
#' data(xcmsexperiment_negative)
#'
#' param <- defaultAnnotationParameters("negative")
#' dbs <- createLipidDbs()
#'
#' candidates <- findMs1LipidCandidates(
#'     xcmsexperiment_negative,
#'     dbs,
#'     param
#' )
#'
#' x <- addCandidateSummaryToChromPeakData(
#'     xcmsexperiment_negative,
#'     candidates
#' )
#'
#' head(xcms::chromPeakData(x))
#'
#' @return Updated `XcmsExperiment`.
#'
#' @export
addCandidateSummaryToChromPeakData <- function(x, candidates) {
  if (!requireNamespace("xcms", quietly = TRUE)) {
    stop("Package 'xcms' is required.", call. = FALSE)
  }

  cpd <- as.data.frame(xcms::chromPeakData(x))
  peak_ids <- rownames(xcms::chromPeaks(x))

  cpd$has_lipid_candidate <- FALSE
  cpd$n_lipid_candidates <- 0L

  if (nrow(candidates)) {
    tab <- table(candidates$chrom_peak_id)
    idx <- match(names(tab), peak_ids)

    keep <- !is.na(idx)
    idx <- idx[keep]
    tab <- tab[keep]

    cpd$has_lipid_candidate[idx] <- TRUE
    cpd$n_lipid_candidates[idx] <- as.integer(tab)
  }

  xcms::chromPeakData(x) <- as.data.frame(cpd)
  x
}

#' Get candidate MS1 chromPeak IDs
#'
#' @param candidates Candidate table returned by [findMs1LipidCandidates()].
#'
#' @return Character vector of unique MS1 chromPeak IDs.
#'
#' @noRd
#'
#' @keywords internal
.get_candidate_peak_ids <- function(candidates) {
  if (!nrow(candidates)) {
    return(character())
  }

  unique(candidates$chrom_peak_id)
}

#' Filter candidates supported only by a weak unique adduct
#'
#' Remove MS1 candidates whose adduct is marked as `exclude_if_unique = 1`
#' when that lipid candidate is supported by a single adduct only.
#'
#' The filtering is applied after coeluting adduct grouping and adduct-group
#' scoring. Therefore, a candidate such as `PC M-CH3` in negative mode is kept
#' if another coeluting adduct supports the same class and sum composition, but
#' removed if it is the only supporting adduct.
#'
#' @param candidates `data.frame` returned by [groupCoelutingAdducts()] after
#' adduct scoring.
#'
#' @return Filtered candidate table.
#'
#' @noRd
#'
#' @keywords internal
.filter_unique_unsupported_adducts <- function(candidates) {
  if (!nrow(candidates)) {
    return(candidates)
  }

  if (!"exclude_if_unique" %in% colnames(candidates)) {
    candidates$exclude_if_unique <- 0L
  }

  if (!"adduct_group_n_adducts" %in% colnames(candidates)) {
    candidates <- .score_adduct_groups(candidates)
  }

  candidates$exclude_if_unique[is.na(candidates$exclude_if_unique)] <- 0L

  keep <- !(
    candidates$exclude_if_unique == 1L &
      candidates$adduct_group_n_adducts <= 1L
  )

  out <- candidates[keep, , drop = FALSE]
  rownames(out) <- NULL
  out
}
